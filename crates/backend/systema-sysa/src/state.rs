use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::time::Instant;
use tokio::task::AbortHandle;

use parking_lot::RwLock;
use sysa::event_bus::EventBus;
use tokio::sync::mpsc;
use tokio::sync::RwLock as TokioRwLock;
use tracing::info;
use uuid::Uuid;

use systema_sysf::ir::UnitIR;

use crate::unit::types::{SliceSection, SuccessAction, UnitFile, UnitKind};

/// systemd's root slice unit name (`-.slice`).
///
/// Like other special units it is perpetual: it always exists in memory and
/// is always `active`, wrapping every other unit's cgroup at `/`.
pub const ROOT_SLICE_NAME: &str = "-.slice";

/// Snapshot of a unit's runtime state, kept up-to-date via `method.result`
/// responses and `unit.state_update` push events.  Read synchronously by
/// control-port snapshots.
#[derive(Debug, Clone, Default)]
pub struct CachedUnitState {
    pub active_state: String,
    pub sub_state: String,
    pub main_pid: u32,
    /// Invocation ID (UUID v4) of the current activation, as reported by
    /// the owning worker (or generated by System A for units that report
    /// none, e.g. mount units).  Cleared when the unit reaches
    /// `inactive`/`dead`.
    pub invocation_id: String,
    /// Realtime µs since the epoch when the unit last entered `active`
    /// (systemd `ActiveEnterTimestamp`).  Reset when leaving `active`.
    pub active_enter_timestamp: u64,
    /// Realtime µs since the epoch when the unit last entered `inactive`
    /// or `failed` (systemd `InactiveEnterTimestamp`).  Reset on re-entry
    /// into `active`.
    pub inactive_enter_timestamp: u64,
    /// Worker-specific extensions (e.g. `last_exit_code`, `last_error`).
    pub extensions: HashMap<String, String>,
    /// PIDs wrapped by a scope unit (transient `PIDs=` property), reported
    /// by the System E worker.  Empty for non-scope units.
    pub pids: Vec<u32>,
    /// D-Bus unique name of the scope's controller (the client that created
    /// the transient scope via `StartTransientUnit`).  Empty when none.
    pub controller: String,
}

