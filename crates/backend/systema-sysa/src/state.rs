/// A registered System Worker connection.
pub struct WorkerEntry {
    pub worker_id: String,
    /// Unit types this worker handles, e.g. ["service"].
    pub unit_types: Vec<String>,
    /// Whether the worker implements the `unit.define` protocol and may be
    /// asked to synthesize definitions for dynamic units of its types.
    pub supports_unit_define: bool,
    /// Whether the worker declared itself ready (`worker.ready` envelope).
    pub ready: bool,
    /// Channel to send pre-encoded envelopes (method calls, etc.).
    pub envelope_tx: mpsc::Sender<bytes::Bytes>,
}

/// A staging area bound to a single worker UID.
#[derive(Debug, Clone)]
pub struct StagingArea {
    pub name: String,
    pub uid: u32,
    pub units: HashMap<String, UnitIR>,
}

/// Validate a staging area name.
///
/// Allowed characters: upper/lowercase letters, `_`, `/`, `\`, `-`.
/// Maximum length: 64 characters.
pub fn is_valid_staging_name(name: &str) -> bool {
    !name.is_empty()
        && name.len() <= 64
        && name
            .bytes()
            .all(|b| b.is_ascii_alphabetic() || matches!(b, b'_' | b'/' | b'\\' | b'-'))
}

